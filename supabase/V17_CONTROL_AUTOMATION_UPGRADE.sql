create table if not exists public.aw_audit_log (
  id bigint generated by default as identity primary key,
  actor_user_id uuid references auth.users(id) on delete set null,
  actor_role text,
  action text not null,
  table_name text not null,
  record_id text,
  before_data jsonb,
  after_data jsonb,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists aw_audit_log_created_idx on public.aw_audit_log(created_at desc);
create index if not exists aw_audit_log_record_idx on public.aw_audit_log(table_name,record_id,created_at desc);

create or replace function public.aw_v17_audit_trigger()
returns trigger language plpgsql security definer set search_path=public as $$
declare rid text; role_name text;
begin
  begin select role into role_name from public.profiles where id=auth.uid(); exception when others then role_name:=null; end;
  if tg_op='DELETE' then rid:=coalesce(to_jsonb(old)->>'id',''); else rid:=coalesce(to_jsonb(new)->>'id',''); end if;
  insert into public.aw_audit_log(actor_user_id,actor_role,action,table_name,record_id,before_data,after_data)
  values(auth.uid(),coalesce(role_name,case when auth.uid() is null then 'system' else 'authenticated' end),lower(tg_op),tg_table_name,rid,
    case when tg_op in('UPDATE','DELETE') then to_jsonb(old) else null end,
    case when tg_op in('INSERT','UPDATE') then to_jsonb(new) else null end);
  return coalesce(new,old);
end $$;

do $$declare t text;begin
  foreach t in array array[
    'payments','enrollments','os_student_course_enrollments','os_hour_ledger','courses','tutors',
    'student_support_tickets','student_reschedule_requests','student_assignment_submissions','tutor_applications'
  ] loop
    if to_regclass('public.'||t) is not null then
      execute format('drop trigger if exists trg_aw_v17_audit on public.%I',t);
      execute format('create trigger trg_aw_v17_audit after insert or update or delete on public.%I for each row execute function public.aw_v17_audit_trigger()',t);
    end if;
  end loop;
end$$;

alter table public.aw_audit_log enable row level security;
drop policy if exists aw_v17_audit_manager_read on public.aw_audit_log;
create policy aw_v17_audit_manager_read on public.aw_audit_log for select to authenticated using(public.is_manager());
