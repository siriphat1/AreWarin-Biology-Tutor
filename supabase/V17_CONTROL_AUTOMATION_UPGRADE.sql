-- 7) Universal Search
-- ------------------------------------------------------------
create or replace function public.aw_v17_search(p_query text)
returns jsonb language plpgsql security definer set search_path=public as $$
declare q text:=trim(coalesce(p_query,'')); result jsonb;
begin
  if not public.is_manager() then raise exception 'Not authorized'; end if;
  if length(q)<2 then return '[]'::jsonb; end if;
  with results as (
    select 'student'::text kind,s.id::text id,coalesce(s.display_name,s.first_name||' '||s.last_name) title,
      concat_ws(' · ',s.student_code,s.phone,s.school) subtitle,'student360' route,100 score
    from public.os_students s where s.deleted_at is null and (s.display_name ilike '%'||q||'%' or s.first_name ilike '%'||q||'%' or s.last_name ilike '%'||q||'%' or s.phone ilike '%'||q||'%' or s.student_code ilike '%'||q||'%')
    union all
    select 'enrollment',e.id::text,coalesce(e.fullname,e.nickname,'Enrollment'),concat_ws(' · ',e.phone,e.receipt_no,e.course_text),'enrollments',90
    from public.enrollments e where e.deleted_at is null and (e.fullname ilike '%'||q||'%' or e.nickname ilike '%'||q||'%' or e.phone ilike '%'||q||'%' or e.receipt_no ilike '%'||q||'%' or e.course_text ilike '%'||q||'%')
    union all
    select 'course',c.id::text,c.name,coalesce(c.short_detail,''),'courses',80 from public.courses c where c.deleted_at is null and (c.name ilike '%'||q||'%' or c.short_detail ilike '%'||q||'%')
    union all
    select 'tutor',t.id::text,t.display_name,coalesce(t.full_name||' · ','')||coalesce(t.role_text,''),'tutors',80 from public.tutors t where t.deleted_at is null and (t.display_name ilike '%'||q||'%' or t.full_name ilike '%'||q||'%')
    union all
    select 'ticket',st.id::text,coalesce(st.ticket_no,'Ticket')||' · '||st.subject,st.category||' · '||st.status,'v17control',75 from public.student_support_tickets st where st.subject ilike '%'||q||'%' or st.description ilike '%'||q||'%' or st.ticket_no ilike '%'||q||'%'
  ), limited as (select * from results order by score desc,title limit 30)
  select coalesce(jsonb_agg(to_jsonb(r) order by score desc,title),'[]'::jsonb) into result from limited r;
  return result;
end$$;
grant execute on function public.aw_v17_search(text) to authenticated;

