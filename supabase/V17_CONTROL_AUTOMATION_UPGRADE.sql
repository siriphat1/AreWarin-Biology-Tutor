-- 9) System Health / integrity
-- ------------------------------------------------------------
create or replace function public.aw_v17_system_health()
returns jsonb language plpgsql security definer set search_path=public as $$
declare issues jsonb; summary jsonb;
begin
  if not public.is_manager() then raise exception 'Not authorized'; end if;
  with i as (
    select 'active_course_payment_mismatch' code,'สูง' severity,'คอร์ส Active แต่ Payment ยังไม่ paid' title,count(*)::int total
    from public.os_student_course_enrollments sce join public.payments p on p.enrollment_id=sce.source_enrollment_id where sce.status in('active','paused','completed') and p.status<>'paid'
    union all
    select 'active_course_enrollment_mismatch','สูง','คอร์ส Active แต่ Enrollment ยังไม่ confirmed',count(*)::int from public.os_student_course_enrollments sce join public.enrollments e on e.id=sce.source_enrollment_id where sce.status in('active','paused','completed') and e.status<>'confirmed'
    union all
    select 'course_without_hour_pool','กลาง','คอร์ส Active ไม่มี Hour Pool',count(*)::int from public.os_student_course_enrollments where status='active' and hour_pool_id is null
    union all
    select 'group_without_members','ต่ำ','Group Locker Active แต่ไม่มีสมาชิก',count(*)::int from public.os_student_groups g where g.status='active' and not exists(select 1 from public.os_student_group_members gm where gm.group_id=g.id and gm.is_active=true)
    union all
    select 'pending_payment_old','กลาง','Payment pending เกิน 3 วัน',count(*)::int from public.payments where status='pending' and created_at<now()-interval '3 days'
    union all
    select 'urgent_ticket','สูง','Support Ticket เร่งด่วนยังไม่ปิด',count(*)::int from public.student_support_tickets where priority='urgent' and status not in('resolved','closed')
  ) select coalesce(jsonb_agg(to_jsonb(i)),'[]'::jsonb),jsonb_build_object('issue_total',coalesce(sum(total),0),'checked_at',now()) into issues,summary from i;
  return jsonb_build_object('summary',summary,'issues',issues);
end$$;
grant execute on function public.aw_v17_system_health() to authenticated;

