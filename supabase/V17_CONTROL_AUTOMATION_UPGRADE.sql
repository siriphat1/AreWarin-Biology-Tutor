create or replace function public.aw_v17_can(p_module text,p_action text default 'view')
returns boolean language plpgsql stable security definer set search_path=public as $$
declare r text; x public.aw_role_permissions;
begin
  select role into r from public.profiles where id=auth.uid();
  if r in('admin','manager') then return true; end if;
  select * into x from public.aw_role_permissions where role_key=r and module_key=p_module;
  if x.role_key is null then select * into x from public.aw_role_permissions where role_key=r and module_key='*'; end if;
  if x.role_key is null then return false; end if;
  return case p_action when 'create' then x.can_create when 'update' then x.can_update when 'delete' then x.can_delete else x.can_view end;
end$$;
grant execute on function public.aw_v17_can(text,text) to authenticated;

