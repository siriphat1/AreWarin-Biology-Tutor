-- 8) Student 360
-- ------------------------------------------------------------
create or replace function public.aw_v17_student_360(p_student_id uuid)
returns jsonb language plpgsql security definer set search_path=public as $$
declare result jsonb;
begin
  if not public.is_manager() then raise exception 'Not authorized'; end if;
  if not exists(select 1 from public.os_students where id=p_student_id) then raise exception 'Student not found'; end if;
  select jsonb_build_object(
    'student',(select to_jsonb(s) from public.os_students s where s.id=p_student_id),
    'courses',coalesce((select jsonb_agg(to_jsonb(x) order by x.created_at desc) from public.os_student_course_enrollments x where x.student_id=p_student_id),'[]'::jsonb),
    'hour_pools',coalesce((select jsonb_agg(to_jsonb(x) order by x.updated_at desc) from public.os_hour_pools x where x.student_id=p_student_id),'[]'::jsonb),
    'hour_ledger',coalesce((select jsonb_agg(to_jsonb(x) order by x.created_at desc) from (select * from public.os_hour_ledger where student_id=p_student_id order by created_at desc limit 100)x),'[]'::jsonb),
    'attendance',coalesce((select jsonb_agg(jsonb_build_object('id',a.id,'status',a.status,'note',a.note,'deducted_hours',coalesce(a.deducted_hours,0),'session_date',s.session_date,'title',s.title,'course_id',s.course_id) order by s.session_date desc) from public.os_student_attendance a join public.os_attendance_sessions s on s.id=a.session_id where a.student_id=p_student_id),'[]'::jsonb),
    'payments',coalesce((select jsonb_agg(to_jsonb(p) order by p.created_at desc) from public.payments p where p.enrollment_id in(select source_enrollment_id from public.os_student_course_enrollments where student_id=p_student_id and source_enrollment_id is not null)),'[]'::jsonb),
    'schedule',coalesce((select jsonb_agg(to_jsonb(e) order by e.start_at desc) from public.student_schedule_events e where e.student_id=p_student_id or e.group_id in(select group_id from public.os_student_group_members where student_id=p_student_id and is_active=true)),'[]'::jsonb),
    'assignments',coalesce((select jsonb_agg(to_jsonb(a) order by coalesce(a.due_at,'2999-01-01'::timestamptz)) from public.student_assignments a where a.student_id=p_student_id or a.course_id in(select course_id from public.os_student_course_enrollments where student_id=p_student_id) or a.group_id in(select group_id from public.os_student_group_members where student_id=p_student_id and is_active=true)),'[]'::jsonb),
    'submissions',coalesce((select jsonb_agg(to_jsonb(x) order by x.submitted_at desc) from public.student_assignment_submissions x where x.student_id=p_student_id),'[]'::jsonb),
    'tickets',coalesce((select jsonb_agg(to_jsonb(x) order by x.updated_at desc) from public.student_support_tickets x where x.student_id=p_student_id),'[]'::jsonb),
    'parent_links',coalesce((select jsonb_agg(jsonb_build_object('id',x.id,'parent_name',x.parent_name,'relationship',x.relationship,'active',x.active,'last_used_at',x.last_used_at,'created_at',x.created_at) order by x.created_at desc) from public.student_parent_links x where x.student_id=p_student_id),'[]'::jsonb),
    'certificates',coalesce((select jsonb_agg(to_jsonb(x) order by x.issued_at desc) from public.student_certificates x where x.student_id=p_student_id),'[]'::jsonb),
    'groups',coalesce((select jsonb_agg(jsonb_build_object('id',g.id,'group_code',g.group_code,'name',g.name,'status',g.status,'course_id',g.course_id,'tutor_id',g.tutor_id)) from public.os_student_group_members gm join public.os_student_groups g on g.id=gm.group_id where gm.student_id=p_student_id and gm.is_active=true),'[]'::jsonb)
  ) into result;
  return result;
end$$;
grant execute on function public.aw_v17_student_360(uuid) to authenticated;

