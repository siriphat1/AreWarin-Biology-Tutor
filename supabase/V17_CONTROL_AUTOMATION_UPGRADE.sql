-- 10) Finance aging
-- ------------------------------------------------------------
create or replace function public.aw_v17_finance_aging()
returns jsonb language sql stable security definer set search_path=public as $$
  select case when public.is_manager() then jsonb_build_object(
    'current',coalesce(sum(amount_submitted) filter(where status='pending' and created_at>=now()-interval '7 days'),0),
    'd8_30',coalesce(sum(amount_submitted) filter(where status='pending' and created_at<now()-interval '7 days' and created_at>=now()-interval '30 days'),0),
    'over30',coalesce(sum(amount_submitted) filter(where status='pending' and created_at<now()-interval '30 days'),0),
    'pending_count',count(*) filter(where status='pending'),
    'paid_30d',coalesce(sum(coalesce(verified_amount,amount_submitted)) filter(where status='paid' and coalesce(verified_at,created_at)>=now()-interval '30 days'),0)
  ) else jsonb_build_object('error','not_authorized') end from public.payments;
$$;
grant execute on function public.aw_v17_finance_aging() to authenticated;

-- ------------------------------------------------------------
-- 11) V17 Student bootstrap: V16 + group broadcasts
-- ------------------------------------------------------------
create or replace function public.student_v17_bootstrap()
returns jsonb language plpgsql security definer set search_path=public as $$
declare sid uuid:=public.aw_my_student_id(); base jsonb;
begin
  if sid is null then raise exception 'Student account is not linked'; end if;
  base:=public.student_v16_bootstrap();
  return base||jsonb_build_object(
    'v17_group_broadcasts',coalesce((select jsonb_agg(jsonb_build_object('id',b.id,'group_id',b.group_id,'group_name',g.name,'title',b.title,'body',b.body,'pinned',b.pinned,'created_at',b.created_at,'expires_at',b.expires_at) order by b.pinned desc,b.created_at desc) from public.os_group_broadcasts b join public.os_student_groups g on g.id=b.group_id where b.visible_to_students=true and (b.expires_at is null or b.expires_at>now()) and b.group_id in(select group_id from public.os_student_group_members where student_id=sid and is_active=true)),'[]'::jsonb)
  );
end$$;
grant execute on function public.student_v17_bootstrap() to authenticated;

